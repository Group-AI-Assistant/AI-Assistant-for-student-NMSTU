      content_of_posts = []
      posts = get_posts_by_this_year(group.removeprefix('https://vk.ru/'))
      content_of_posts.extend(clean_post(post['text']) for post in posts)

      filename = group.removeprefix('https://vk.ru/') + '.txt'
      with open(filename, 'w', encoding='utf-8-sig') as f:
        for post in content_of_posts:
          f.write(post + '\n\n')   # пост + пустая строка
      zipf.write(filename)

