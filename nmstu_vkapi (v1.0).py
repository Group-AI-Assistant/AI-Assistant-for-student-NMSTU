def get_user_date(prompt):
    while True:
        raw = input(prompt).strip()
        try:
            dt = datetime.strptime(raw, "%d.%m.%Y").replace(tzinfo=timezone.utc)
            return dt
        except ValueError:
            print("Неверный формат. Введите дату в виде ДД.ММ.ГГГГ, например 01.01.2025")


print("Введите период, за который нужно собрать посты:")
while True:
  start_date = get_user_date("Дата начала (ДД.ММ.ГГГГ): ")
  end_date = get_user_date("Дата окончания (ДД.ММ.ГГГГ): ")

