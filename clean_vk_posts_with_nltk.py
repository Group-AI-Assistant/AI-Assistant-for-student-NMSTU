import nltk
nltk.download('punkt_tab')
nltk.download('stopwords')

# 2. Импорт библиотек
import io
import string
import zipfile
from collections import defaultdict
from google.colab import files
from nltk.tokenize import word_tokenize
from nltk.corpus import stopwords
from nltk.stem import SnowballStemmer

# 3. Загрузка файлов
print("Загрузите .txt файлы:")
uploaded = files.upload()

# 4. Чтение файлов и разбиение на блоки по пустым строкам
file_blocks = {}
for filename, content in uploaded.items():
    text = content.decode('utf-8')
    # Блоки разделены одной или несколькими пустыми строками
    blocks = [block.strip() for block in text.split('\n\n') if block.strip()]
    file_blocks[filename] = blocks

# 5. Подготовка инструментов NLTK
stemmer_ru = SnowballStemmer('russian')
stemmer_en = SnowballStemmer('english')
stop_ru = set(stopwords.words('russian'))
stop_en = set(stopwords.words('english'))

def normalize_text(text: str) -> set:
    """
    Приводит текст к множеству стемов:
    - нижний регистр,
    - удаление пунктуации,
    - токенизация,
    - удаление стоп-слов,
    - стемминг (русский или английский в зависимости от символов).
    """
    text = text.lower().translate(str.maketrans('', '', string.punctuation))
    tokens = word_tokenize(text)
    stems = []
    for token in tokens:
        if token in stop_ru or token in stop_en:
            continue
        # Если токен содержит кириллицу – используем русский стеммер
        if any('\u0400' <= ch <= '\u04FF' for ch in token):
            stems.append(stemmer_ru.stem(token))
        else:
            stems.append(stemmer_en.stem(token))
    return set(stems)

# 6. Сбор всех блоков с метаданными
all_blocks = []
for filename, blocks in file_blocks.items():
    for idx, block in enumerate(blocks):
        all_blocks.append({
            'filename': filename,
            'index': idx,
            'text': block,
            'normalized': normalize_text(block)
        })

# 7. Поиск дубликатов и семантически близких блоков
def jaccard_similarity(set1: set, set2: set) -> float:
    """Jaccard-сходство двух множеств."""
    if not set1 or not set2:
        return 0.0
    return len(set1 & set2) / len(set1 | set2)

# Порог схожести:
#Порог 1.0 - Отсекает только идентичные строки (слово в слово)
#Порог 0.95–0.99 - Удаляются почти идентичные блоки, отличающиеся одним-двумя словами
#Порог 0.8-0.9 - Ловит перефразировки с небольшими изменениями
#Порог 0.6-0.7 - Может удалять блоки, которые лишь частично пересекаются по смыслу/словам.
#Ниже порога 0.6 не рекомендуется выставлять, дабы избежать удаления строк имеющих похожие слова, но разный смысл
SIMILARITY_THRESHOLD = 0.6

unique_blocks = []
for block in all_blocks:
    is_duplicate = False
    for existing in unique_blocks:
        if jaccard_similarity(block['normalized'], existing['normalized']) >= SIMILARITY_THRESHOLD:
            is_duplicate = True
            break
    if not is_duplicate:
        unique_blocks.append(block)

# 8. Восстановление очищенных файлов
cleaned_files = defaultdict(list)
for block in unique_blocks:
    cleaned_files[block['filename']].append(block['text'])

# 9. Сохранение очищенных файлов и упаковка в ZIP
for filename, blocks in cleaned_files.items():
    cleaned_name = f"cleaned_{filename}"
    with open(cleaned_name, 'w', encoding='utf-8') as f:
        f.write('\n\n'.join(blocks))

with zipfile.ZipFile('cleaned_files.zip', 'w') as zipf:
    for filename in cleaned_files:
        zipf.write(f"cleaned_{filename}", arcname=f"cleaned_{filename}")

# 10. Скачивание архива
files.download('cleaned_files.zip')